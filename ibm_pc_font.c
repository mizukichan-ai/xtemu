/* Get character bitmap function */
const uint8_t* ibm_pc_get_char_bitmap(uint8_t character) {
    if (character < 32) {
        return ibm_pc_font_control[character];
    } else if (character < 128) {
        return ibm_pc_font_printable[character - 32];
    } else if (character < 256) {
        return ibm_pc_font_extended[character - 128];
    } else {
        return ibm_pc_font_control[0]; /* Default to null character */
    }
}